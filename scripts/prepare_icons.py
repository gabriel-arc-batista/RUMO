"""Subset the Lucide icon font to the glyphs RUMO draws and write the name map.

Usage: python scripts/prepare_icons.py PATH/lucide.ttf PATH/info.json
Source: lucide-static 0.460.0 (ISC). The download stays outside the repository;
only the subset, its license and the generated map are versioned.
"""

import json
import sys
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
NAMES = """
house repeat book-open crosshair brain chart-column history swords trophy map
settings timer play pause plus minus check x chevron-left chevron-right
chevron-down flame target sparkles compass shield coins book-marked lock star
panel-left sun moon bell circle-help zap feather backpack sword crown gem heart
sprout leaf battery-low quote external-link maximize trash-2 flag mountain
footprints hourglass list-checks calendar award medal castle info
triangle-alert user circle-check circle rotate-ccw skull lamp telescope
scroll-text graduation-cap square-check square arrow-right eye pencil ellipsis
undo-2 search palette swatch-book shirt shield-half axe hammer wand-sparkles
wand rabbit bird dog cat squirrel turtle paw-print glasses crown gem sparkle
venetian-mask
""".split()


def main(font, info):
    table = json.loads(Path(info).read_text(encoding="utf-8"))
    codes = {name: int(table[name]["encodedCode"].strip("\\"), 16) for name in NAMES}
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    loaded = subset.load_font(font, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=list(codes.values()))
    subsetter.subset(loaded)
    subset.save_font(loaded, ROOT / "assets/fonts/RUMO-Icons.ttf", options)
    lines = [
        '"""Generated by scripts/prepare_icons.py from Lucide (ISC). Do not edit."""',
        "",
        "ICONS = {",
        *(f'    "{name}": "\\u{code:04x}",' for name, code in sorted(codes.items())),
        "}",
        "",
    ]
    (ROOT / "icons.py").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:3])
