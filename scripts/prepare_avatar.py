def hair_shade(pen, image, mask, palette, top=62, bottom=110, strands=None, depth=3.0):
    base, shade, light = palette
    paint(image, mask, base)
    paint(image, vertical(pen, mask, top, bottom), shade, 0.6)
    paint(image, vertical(pen, mask, bottom, top), light, 0.35)
    volume(pen, image, mask, shade, light, depth, 2.8, 0.8, 0.4)
    for points, kind in strands or []:
        stroke(
            pen,
            image,
            points,
            shade if kind == "dark" else light,
            0.55,
            0.45 if kind == "dark" else 0.35,
            mask,
            soft=0.2,
        )


def radial_strands(crown, ends, bend=4):
    lines = []
    for i, end in enumerate(ends):
        mid = (
            (crown[0] + end[0]) / 2 + (bend if end[0] < crown[0] else -bend),
            (crown[1] + end[1]) / 2,
        )
        lines.append(([crown, mid, end], "dark" if i % 2 else "light"))
    return lines


def curls(pen, centers, radius):
    mask = pen.mask()
    draw = ImageDraw.Draw(mask)
    for x, y in centers:
        draw.ellipse(pen.box(x - radius, y - radius, x + radius, y + radius), fill=255)
    return mask


def curl_texture(pen, image, centers, radius, palette, region):
    _, shade, light = palette
    for x, y in centers:
        stroke(
            pen,
            image,
            [
                (x - radius * 0.6, y + radius * 0.2),
                (x, y + radius * 0.75),
                (x + radius * 0.6, y + radius * 0.2),
            ],
            shade,
            0.7,
            0.35,
            region,
        )
        stroke(
            pen,
            image,
            [
                (x - radius * 0.5, y - radius * 0.2),
                (x - radius * 0.1, y - radius * 0.55),
            ],
            light,
            0.6,
            0.45,
            region,
        )


def ring(cx, cy, rx, ry, count, start=0, end=360):
    return [
        (cx + rx * math.cos(math.radians(a)), cy + ry * math.sin(math.radians(a)))
        for a in [start + (end - start) * i / count for i in range(count)]
    ]


