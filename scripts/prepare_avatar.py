def eye_geometry(ex, ey, inward, shape):
    _, _, w, h, tilt, _, _ = shape
    inner = (ex + inward * w / 2, ey + 0.4)
    outer = (ex - inward * w / 2, ey + tilt)
    upper = [
        inner,
        (ex + inward * w * 0.22, ey - h * 0.56),
        (ex - inward * w * 0.12, ey - h * 0.62),
        (ex - inward * w * 0.36, ey - h * 0.42 + tilt * 0.4),
        outer,
    ]
    lower = [
        outer,
        (ex - inward * w * 0.22, ey + h * 0.36 + tilt * 0.2),
        (ex + inward * w * 0.16, ey + h * 0.36),
        inner,
    ]
    return upper, lower


