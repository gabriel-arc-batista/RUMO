def jobs():
    skins = A.ids(A.SKINS)
    hair_colors = A.ids(A.HAIR_COLORS)
    for sex in A.ids(A.SEXES):
        for key in skins:
            yield ("body", sex, key), f"body-{sex}-{key}"
            yield ("head", sex, key), f"head-{sex}-{key}"
    for kind in A.ids(A.EARS):
        for key in skins:
            yield ("ears", kind, key), f"ears-{kind}-{key}"
    for shape in A.ids(A.EYE_SHAPES):
        yield ("lashes", shape), f"lashes-{shape}"
        for color in A.ids(A.EYE_COLORS):
            yield ("eyes", shape, color), f"eyes-{shape}-{color}"
    for kind in A.ids(A.BROWS):
        for color in hair_colors:
            yield ("brows", kind, color), f"brows-{kind}-{color}"
    for style, _, front, back in A.HAIR_STYLES:
        for color in hair_colors:
            if front:
                yield ("hair_front", style, color), f"hair-{style}-{color}"
            if back:
                yield ("hair_back", style, color), f"hairback-{style}-{color}"


DRAW = dict(
    body=body,
    head=head,
    ears=ears,
    eyes=eyes,
    lashes=lashes,
    brows=brows,
    hair_front=hair_front,
    hair_back=hair_back,
)


def render(job):
    (kind, *args), name = job
    for pen in (FULL, BUST):
        pen.save(DRAW[kind](pen, *args), name)
    return name


def compose(pen, look):
    """Stack one look on ``pen`` (used for base.png and the default avatars)."""
    back, front = A.layers(look)
    image = pen.new()
    for name in back + front:
        kind, rest = name.split("-", 1)
        args = {
            "hairback": ("hair_back",),
            "hair": ("hair_front",),
        }.get(kind, (kind,))
        parts = split_name(kind, rest)
        image.alpha_composite(DRAW[args[0]](pen, *parts))
    return image


def split_name(kind, rest):
    if kind in ("hair", "hairback"):
        style = next(s for s in A.ids(A.HAIR_STYLES) if rest.startswith(s + "-"))
        return style, rest[len(style) + 1 :]
    if kind in ("body", "head"):
        sex, skin_key = rest.split("-", 1)
        return sex, skin_key
    if kind == "lashes":
        return (rest,)
    first = rest.split("-", 1)
    return first[0], first[1]


def main():
    work = list(jobs())
    with ProcessPoolExecutor() as pool:
        for count, _ in enumerate(pool.map(render, work, chunksize=4), 1):
            if count % 50 == 0:
                print(f"{count}/{len(work)} camadas")
    print(f"{len(work)} camadas x 2 escalas em {OUT}")


if __name__ == "__main__":
    main()
