def lashes(pen, shape_key):
    shape = A.option(A.EYE_SHAPES, shape_key)
    image = pen.new()
    for ex, ey, inward in EYES:
        upper, _ = eye_geometry(ex, ey, inward, shape)
        stroke(pen, image, upper[1:], LID, 1.5, 1)
        # Short flicks on the outer third, pointing away from the nose and up.
        for k, (out, up) in enumerate(((1.7, 1.1), (1.3, 1.8), (0.7, 2.0))):
            sx, sy = upper[-1 - k]
            stroke(
                pen,
                image,
                [(sx, sy), (sx - inward * out, sy - up)],
                LID,
                0.55,
                0.9,
                smooth=False,
            )
    return image


