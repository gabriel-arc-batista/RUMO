class Pen:
    """Maps the 300x380 design grid to one output (4x supersampled)."""

    def __init__(self, folder, size, scale, ox, oy):
        self.folder, self.out = folder, size
        self.s, self.ox, self.oy = scale * K, ox, oy
        self.size = (size[0] * K, size[1] * K)

    def p(self, x, y):
        return ((x - self.ox) * self.s, (y - self.oy) * self.s)

    def pts(self, seq):
        return [self.p(x, y) for x, y in seq]

    def box(self, x0, y0, x1, y1):
        (a, b), (c, d) = self.p(x0, y0), self.p(x1, y1)
        return [min(a, c), min(b, d), max(a, c), max(b, d)]

    def r(self, value):
        return value * self.s

    def w(self, value):
        return max(1, round(value * self.s))

    def new(self):
        return Image.new("RGBA", self.size, (0, 0, 0, 0))

    def mask(self):
        return Image.new("L", self.size, 0)

    def save(self, image, name):
        folder = OUT / self.folder
        folder.mkdir(parents=True, exist_ok=True)
        image.resize(self.out, Image.LANCZOS).save(
            folder / f"{name}.png", optimize=True
        )


