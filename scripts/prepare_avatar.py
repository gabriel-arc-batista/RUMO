def brows(pen, kind, color_key):
    base, shade, light = hair_palette(color_key)
    color = shade if color_key in ("platinado", "grisalho", "loiro") else base
    image = pen.new()
    a, b, c, thick, thin = BROW_SPINES[kind]
    for ex, ey, inward in EYES:
        by = ey - 7.2
        spine = [(ex + inward * x, by + y) for x, y in (a, b, c)]
        line = spline(spine, closed=False, samples=12)
        top, bottom = [], []
        for i, (x, y) in enumerate(line):
            t = i / (len(line) - 1)
            half = (thick * (1 - t) + thin * t) / 2
            top.append((x, y - half))
            bottom.append((x, y + half * 0.8))
        mask = poly_mask(pen, top + bottom[::-1], smooth=False)
        paint(image, blur(pen, mask, 0.15), color, 0.95)
        rng = random.Random(kind + color_key + str(inward))
        for i in range(0, len(line) - 1, 2):
            x, y = line[i]
            stroke(
                pen,
                image,
                [(x, y + 0.6), (x - inward * 1.4, y - 0.7 + rng.uniform(-0.2, 0.2))],
                mix(color, "#000000", 0.25),
                0.3,
                0.6,
                mask,
                smooth=False,
            )
    return image


