import { chromium } from "playwright-core";
import { fileURLToPath } from "node:url";
const email = process.argv[2];
if (!email) throw new Error("Informe o e-mail sintético criado por extras.mjs.");
const b = await chromium.launch({ executablePath: process.env.CHROME ?? "/usr/bin/google-chrome", headless: true });
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto("http://localhost:4175/entrar");
await page.getByLabel("E-mail").fill(email);
await page.getByLabel("Senha").fill("senha-exemplo-123");
await page.locator("form").getByRole("button", { name: "Entrar" }).click();
await page.waitForURL("http://localhost:4175/");
await page.goto("http://localhost:4175/campo/aula/exemplo.aula.juncoes/ler?pagina=2");
await page.locator(".pdf-page canvas").first().waitFor();
await page.waitForTimeout(2500);
const p2 = await page.locator("#li-pagina-2").isChecked();
const p1 = await page.locator("#li-pagina-1").isChecked();
if (!p2 || p1) throw new Error(`Leitura divergente no site: p1=${p1}, p2=${p2}`);
console.log(`${p2 && !p1 ? "ok  " : "FALHA"} site mostra a página 2 marcada no desktop (p1=${p1}, p2=${p2})`);
await page.goto("http://localhost:4175/flashcards/deck/exemplo.deck.sql");
await page.waitForTimeout(1500);
const row = await page.locator(".card-row", { hasText: "junção interna (INNER JOIN)" }).innerText();
if (!row.includes("Volta")) throw new Error("A revisão do desktop não apareceu no site.");
console.log(`${row.includes("Volta") ? "ok  " : "FALHA"} revisão feita no desktop agenda o cartão no site — ${row.replace(/\n/g, " · ")}`);
await page.screenshot({ path: fileURLToPath(new URL("./.shots/desktop-para-site.png", import.meta.url)) });
await b.close();
