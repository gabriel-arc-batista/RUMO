// Site mostra o que o app enviou: nome/aparência, ciclo no Início e vitória na Arena.
import { chromium } from "playwright-core";
import { fileURLToPath } from "node:url";

const email = process.argv[2];
const BASE = process.env.BASE ?? "http://localhost:4175";
const b = await chromium.launch({ executablePath: process.env.CHROME ?? "/usr/bin/google-chrome", headless: true });
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
let ok = 0, total = 0;
const check = (name, cond, detail = "") => { total++; if (cond) ok++; console.log(`${cond ? "ok  " : "FALHA"} ${name}${detail ? ` — ${detail}` : ""}`); };
await page.goto(`${BASE}/entrar`);
await page.getByLabel("E-mail").fill(email);
await page.getByLabel("Senha").fill("senha-exemplo-123");
await page.locator("form").getByRole("button", { name: "Entrar" }).click();
await page.waitForURL(`${BASE}/`);
await page.waitForTimeout(2500);
await page.screenshot({ path: fileURLToPath(new URL("./.shots/perfil-inicio.png", import.meta.url)) });
const home = await page.locator("main").innerText();
check("nome do personagem vindo do app", home.includes("Exploradora"));
check("ciclo do app contextualiza o Início", home.includes("No ciclo do aplicativo") && home.includes("Bancos de dados"), home.match(/No ciclo[^\n]*/)?.[0]);
check("sugestão de questões usa a matéria do ciclo", home.includes("Questões de Bancos de dados"));
const hair = await page.locator(".home-character .portrait img").evaluateAll((imgs) => imgs.map((i) => i.getAttribute("src")).join(" "));
check("retrato usa a aparência do app", hair.includes("hair-longo-ruivo"), hair.match(/hair-[^ ]+/)?.[0]);
await page.goto(`${BASE}/arena/sessao?assunto=topic.bd.normalizacao`);
await page.locator(".question").waitFor();
await page.locator(".option", { hasText: "depende transitivamente" }).click();
await page.getByRole("button", { name: "Confirmar resposta" }).click();
await page.locator(".result-title").waitFor({ timeout: 10000 });
check("primeiro acerto aparece como vitória", (await page.locator(".result-title").innerText()).includes("Vitória"));
await page.goto(`${BASE}/conta`);
await page.waitForTimeout(2500);
await page.screenshot({ path: fileURLToPath(new URL("./.shots/perfil-conta.png", import.meta.url)) });
const conta = await page.locator(".account-grid").innerText();
check("conta mostra vitórias do serviço", /\n1\nvitórias na Arena/.test(conta), conta.match(/\d+\nvitórias na Arena/)?.[0]);
check("conta diz que a aparência veio do app", conta.includes("vindos do aplicativo"));
check("sem erros de página", errors.length === 0, errors.join(" | "));
console.log(`${ok}/${total} verificações ok`);
await b.close();
